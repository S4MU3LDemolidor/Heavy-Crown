export interface Glyph {
  w: number;
  rows: string[];
}

const GLYPHS = new Map<string, Glyph>();
for (const [ch, s] of Object.entries(G)) {
  const rows = s.split('|');
  GLYPHS.set(ch, { w: rows[0].length, rows });
}

export const LINE_H = 10;
const SPACE_W = 3;

export function glyph(ch: string): Glyph | undefined {
  return GLYPHS.get(ch) ?? GLYPHS.get(ch.toUpperCase());
}

export function textWidth(text: string): number {
  let w = 0;
  for (const ch of text) w += ch === ' ' ? SPACE_W : (glyph(ch)?.w ?? 3) + 1;
  return Math.max(0, w - 1);
}

/** Calls plot(x, y) for every inked pixel of `text` with its top-left at (x, y). */
export function rasterText(text: string, x: number, y: number, plot: (px: number, py: number) => void): void {
  let cx = x;
  for (const ch of text) {
    if (ch === ' ') {
      cx += SPACE_W;
      continue;
    }
    const g = glyph(ch);
    if (!g) {
      cx += 4;
      continue;
    }
    g.rows.forEach((row, ry) => {
      for (let rx = 0; rx < row.length; rx++) if (row[rx] === '#') plot(cx + rx, y + ry);
    });
    cx += g.w + 1;
  }
}

/** Splits text into lines no wider than `maxW` pixels. */
export function wrapText(text: string, maxW: number): string[] {
  const out: string[] = [];
  for (const para of text.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const next = line ? `${line} ${word}` : word;
      if (textWidth(next) > maxW && line) {
        out.push(line);
        line = word;
      } else line = next;
    }
    out.push(line);
  }
  return out;
}
