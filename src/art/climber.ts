/** How far the upper body leans forward at each load tier (pixels at the top of the head). */
const LEAN = [0, 0, 0, 1, 2];

/** Shears the rows above `pivot` forward (right) by up to `px` pixels at the top: the body leans into the load. */
function lean(pose: PixelBuffer, px: number, pivot: number): PixelBuffer {
  if (!px) return pose;
  const out = new PixelBuffer(pose.w, pose.h);
  for (let y = 0; y < pose.h; y++) {
    const dx = y >= pivot ? 0 : Math.round((px * (pivot - y)) / pivot);
    for (let x = 0; x < pose.w; x++) {
      const c = pose.get(x, y);
      if (c >>> 24) out.set(x + dx, y, c);
    }
  }
  return out;
}

export interface FrameInfo {
  /** Top-left of the frame in the sheet. */
  sx: number;
  sy: number;
  /** Neck point (scarf attaches here), in frame coordinates, facing right. */
  neck: [number, number];
  /** Top-left of the pack in frame coordinates (facing right), and its size. */
  pack: [number, number, number, number];
}

export interface ClimberSheet {
  sheet: PixelBuffer;
  /** frames[tier][bodyFrame] */
  frames: Record<BodyFrame, FrameInfo>[];
}

export function buildClimberSheet(): ClimberSheet {
  const sheet = new PixelBuffer(BODY_FRAMES.length * FRAME_W, 5 * FRAME_H);
  const frames: Record<BodyFrame, FrameInfo>[] = [];
  for (let tier = 0; tier < 5; tier++) {
    const row = {} as Record<BodyFrame, FrameInfo>;
    BODY_FRAMES.forEach((name, i) => {
      const p = POSES[name];
      // the pose grid sits on the frame's feet row, centred on FEET_X
      const ox = FEET_X - Math.floor(p.grid.w / 2);
      const oy = FEET_Y + 1 - p.grid.h;
      const pivot = p.grid.h - 9;
      const leanPx = p.lying ? 0 : LEAN[tier];
      const body = lean(p.grid, leanPx, pivot);
      const shift = (y: number) => (y >= pivot ? 0 : Math.round((leanPx * (pivot - y)) / pivot));
      const pack = PACKS[tier];
      // the pack hangs on the back (or, seen from behind, over it), its bottom near the belt
      const bx = p.back[0] + shift(p.back[1]);
      const px = ox + (p.front ? bx - Math.floor(pack.w / 2) : bx - pack.w + 3);
      const py = oy + p.back[1] + PACK_DROP - pack.h;
      const frame = new PixelBuffer(FRAME_W, FRAME_H);
      if (!p.front) frame.blit(pack, px, py);
      frame.blit(body, ox, oy);
      if (p.front) frame.blit(pack, px, py);
      frame.selout(OUTLINE, OUTLINE_MIX);
      const sx = i * FRAME_W;
      const sy = tier * FRAME_H;
      sheet.blit(frame, sx, sy);
      row[name] = { sx, sy, neck: [ox + p.neck[0] + shift(p.neck[1]), oy + p.neck[1]], pack: [px, py, pack.w, pack.h] };
    });
    frames.push(row);
  }
  return { sheet, frames };
}
