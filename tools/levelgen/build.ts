/**
 * Generates the levels listed in specs.ts, validates each with the climbability checker and writes
 * src/content/levels/gen/lNN.ts plus the index.   npm run levels:gen [ids...]
 */
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { L1 } from '../../src/content/levels/l1-overgrown-base';
import { L2 } from '../../src/content/levels/l2-drowned-cistern';
import { L3 } from '../../src/content/levels/l3-bell-hall';
import { L4 } from '../../src/content/levels/l4-lightless-floors';
import { L5 } from '../../src/content/levels/l5-frozen-spire';
import type { LevelDef } from '../../src/game/level';
import { generate } from './gen';
import { SPECS } from './specs';

const FIXED: Record<number, { def: LevelDef; name: string; file: string }> = {
  1: { def: L1, name: 'L1', file: './l1-overgrown-base' },
  7: { def: L2, name: 'L2', file: './l2-drowned-cistern' },
  13: { def: L3, name: 'L3', file: './l3-bell-hall' },
  19: { def: L4, name: 'L4', file: './l4-lightless-floors' },
  25: { def: L5, name: 'L5', file: './l5-frozen-spire' },
};
const OUT = 'src/content/levels/gen';
const pad = (n: number) => String(n).padStart(2, '0');

/** Formats a value as TypeScript source with single-quoted strings. */
function fmt(v: unknown, indent = ''): string {
  if (typeof v === 'string') return `'${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (Array.isArray(v)) {
    if (v.every((x) => typeof x !== 'object')) return `[${v.map((x) => fmt(x)).join(', ')}]`;
    return `[\n${v.map((x) => `${indent}  ${fmt(x, indent + '  ')},`).join('\n')}\n${indent}]`;
  }
  if (v && typeof v === 'object') {
    const e = Object.entries(v as Record<string, unknown>);
    const flat = e.every(([, x]) => typeof x !== 'object' || (x && !Array.isArray(x) && Object.values(x).every((y) => typeof y !== 'object')));
    const key = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : fmt(k));
    if (flat && e.length <= 6 && JSON.stringify(v).length < 90) return `{ ${e.map(([k, x]) => `${key(k)}: ${fmt(x)}`).join(', ')} }`;
    return `{\n${e.map(([k, x]) => `${indent}  ${key(k)}: ${fmt(x, indent + '  ')},`).join('\n')}\n${indent}}`;
  }
  return 'undefined';
}

function emit(def: LevelDef, name: string, seed: number): string {
  const { screens, ...rest } = def;
  const head = fmt(rest, '').replace(/\n}$/, '');
  const body = screens.map((rows) => `    [\n${rows.map((r) => `      '${r}',`).join('\n')}\n    ],`).join('\n');
  return [
    "import type { LevelDef } from '../../../game/level';",
    '',
    `/** Level ${def.id} — ${name}. Generated by tools/levelgen (seed ${seed}); edit tools/levelgen/specs.ts, not this file. */`,
    `export const L${pad(def.id)}: LevelDef = ${head}`,
    '  screens: [',
    body,
    '  ],',
    '};',
    '',
  ].join('\n');
}

async function main() {
  const only = new Set(process.argv.slice(2).map(Number));
  if (!existsSync(OUT)) mkdirSync(OUT, { recursive: true });
  const levels = new Map<number, LevelDef>();
  for (const [id, f] of Object.entries(FIXED)) levels.set(Number(id), f.def);
  // levels not being regenerated come from their files
  for (const spec of SPECS) {
    if (only.size && !only.has(spec.id) && existsSync(`${OUT}/l${pad(spec.id)}.ts`)) {
      const mod = await import(`../../${OUT}/l${pad(spec.id)}.ts`);
      levels.set(spec.id, mod[`L${pad(spec.id)}`]);
    }
  }
  let failed = 0;
  for (const spec of [...SPECS].sort((a, b) => a.id - b.id)) {
    if (only.size && !only.has(spec.id)) continue;
    const prev = levels.get(spec.id - 1);
    if (!prev) {
      console.log(`✗ level ${spec.id}: level ${spec.id - 1} is missing`);
      failed++;
      continue;
    }
    const next = FIXED[spec.id + 1]?.def;
    const t0 = performance.now();
    try {
      const out = generate({ spec, prev, next }, Number(process.env.GEN_TRIES) || 400);
      levels.set(spec.id, out.level);
      writeFileSync(`${OUT}/l${pad(spec.id)}.ts`, emit(out.level, spec.name, out.seed));
      console.log(`✓ level ${spec.id} ${spec.name}: seed ${out.seed} (${out.tries} tries, ${out.route.length} ledges, ${Math.round(performance.now() - t0)} ms)`);
    } catch (e) {
      console.log(`✗ ${(e as Error).message}`);
      failed++;
    }
  }
  // the index lists every level that exists, bottom to top
  const files = new Set(readdirSync(OUT).filter((f) => /^l\d\d\.ts$/.test(f)).map((f) => Number(f.slice(1, 3))));
  const lines = ["import type { LevelDef } from '../../game/level';"];
  const names: string[] = [];
  for (let id = 1; id <= 30; id++) {
    if (FIXED[id]) {
      lines.push(`import { ${FIXED[id].name} } from '${FIXED[id].file}';`);
      names.push(FIXED[id].name);
    } else if (files.has(id)) {
      lines.push(`import { L${pad(id)} } from './gen/l${pad(id)}';`);
      names.push(`L${pad(id)}`);
    } else break;
  }
  lines.push('', '/** The tower\'s levels, bottom to top. */', `export const LEVELS: LevelDef[] = [${names.join(', ')}];`, '');
  writeFileSync('src/content/levels/index.ts', lines.join('\n'));
  console.log(`index: ${names.length} levels`);
  process.exit(failed ? 1 : 0);
}
void main();
